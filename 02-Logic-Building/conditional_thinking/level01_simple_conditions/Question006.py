def main():
    # Question 6: Take two numbers and print the larger one.
    first = 20
    second = 35

    if first > second:
        print(first)
    else:
        print(second)


if __name__ == "__main__":
    main()


"""
Explanation:
The variables `first` and `second` hold the two numbers being compared.

The condition `first > second` checks whether `first` is larger than `second`.

- If the condition is True, `first` is printed.
- Otherwise, `second` is printed.

Only the branch whose condition becomes true executes.
"""